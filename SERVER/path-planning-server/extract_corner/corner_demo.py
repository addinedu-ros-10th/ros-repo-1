def corner():
    # ---- 시작점, 목표점 ----
    start = (5, 60)   # (x, y)
    goal  = (27,63)
    # ---- 방향 정보 ----

    inflated = inflate_costmap(grid, radius=2)
    path = right_angle_astar(start, goal, inflated)
    corners = extract_corners(path)
    print("\n직각 waypoint:")
    print(corners, "\n")

    # ---- 결과 출력 ----
    if not path:
        print("❌ 경로를 찾을 수 없습니다.")
    else:
        print(path)
        print("시작점:", start, "→ 목표점:", goal)

        # 터미널에 맵 ASCII 표시
        disp = np.full_like(grid, fill_value="·", dtype='<U1')  # 자유공간
        disp[grid == 1] = "#"  # 장애물

        # 경로 표시
        for (x, y, _) in path:
            disp[y, x] = "o"

        sx, sy = start
        gx, gy = goal
        disp[sy, sx] = "S"
        disp[gy, gx] = "G"
        
        print("\n--- Map View ---")
        for row in disp:
            print("".join(row))

        draw_path_1(grid, start, goal, path, title="Right-Angle Path")



if __name__ == '__main__':
    corner()
